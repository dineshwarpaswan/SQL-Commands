   Select sum(Sallary) FROM employee;  -- जैसे कि :-  Sallary नाम के कॉलम के सभी वैल्यू को जोड़ देगा।

   Select avg(sallary) from employee;  -- जैसे कि:-  Sallary नाम के कॉलम की सभी वैल्यू का एवरेज निकाल देगा

   select count(city) from employee;  -- जैसे कि :-  city नाम के कॉलम की सभी शहरों को गिन देगा।

   SELECT max(age) From employee;  -- जैसे कि:-  Age नाम के कॉलम में सबसे ज्यादा किसकी Age है।

